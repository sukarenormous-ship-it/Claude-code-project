    cps = cost / sets
    jump = D(3)
    per = jump + cps
    n16 = int(ceil1 / per)
    out["v16"] = {"กระโดด": i(jump), "ต่อชุด": num(per), "เพดาน": num(ceil1), "หาร": q(ceil1 / per, 2), "ชุด": n16,
                  "เสีย": num(-n16 * per), "เปอร์เซ็นต์ทุน": q(n16 * per / capP * 100, 2),
                  "ชุดเดิม": i(g("ch14.v2.กฎ1ทางรอด.ชุดที่ไม่เกินกฎ")), "เสียเดิม": num(g("ch14.v2.กฎ1ทางรอด.เสียถ้ากระโดด"))}

    # ── v17 · บท 15: ต้นทุนไปกลับ 4 แทน 2 ──
    o4 = [o - 2 for o in outs]
    ev4 = sum(p * o for p, o in zip(mix, o4))
    var4 = sum(p * o * o for p, o in zip(mix, o4)) - ev4 * ev4
    sd4 = var4.sqrt()
    ratio = 2 * Dq(sd4) / ev4
    nraw = (2 * sd4 / ev4) ** 2
    out["v17"] = {"ชนะ": i(o4[0]), "เสมอ": i(o4[1]), "แพ้": i(o4[2]), "ค่าคาดหวัง": num(ev4),
                  "ค่าเฉลี่ยกำลังสอง": num(sum(p * o * o for p, o in zip(mix, o4))), "ความแปรปรวน": q(var4, 2),
                  "sd": q(sd4, 2), "sdเดิม": num(g("ch15.v2.จำนวนรอบ.0.ระยะแกว่งต่อไม้")),
                  "สองsdหาร": q(ratio, 2), "ไม้ก่อนปัด": q(nraw, 1), "ไม้": int(nraw.to_integral_value(rounding="ROUND_CEILING")),
                  "ไม้เดิม": i(g("ch15.v2.จำนวนรอบ.0.ไม้ที่ต้องมี")),
                  "ผิดสองเท่า": i(2 * g("ch15.v2.จำนวนรอบ.0.ไม้ที่ต้องมี"))}

    # ── v18 · บท 16: สัญญาณออกมาตอนคำสั่งยังค้าง ──
    held, pend = g("ch16.v2.คำสั่งค้าง.ได้"), g("ch16.v2.คำสั่งค้าง.ค้าง")
    out["v18"] = {"ถือB": i(held), "ค้างB": i(pend), "สูตร": i(0 - held - pend), "หลังยกเลิก": i(0 - held),
                  "ถ้าส่งตามสูตรแล้วค้างถูกยกเลิก": i(held + (0 - held - pend)), "ขาA": i(-g("บัญชีมิน.คู่.จำนวนA"))}

    # ── v19 · บท 17: แปดไม้เดิม สลับลำดับ ──
    def path(seq):
        cum, peak, dd, rows = 0, 0, 0, []
        for x in seq:
            cum += x
            peak = max(peak, cum)
            dd = max(dd, peak - cum)
            rows.append(cum)
        return rows, dd, peak
    w, t, l = (int(o) for o in outs)
    seqA = [w, w, l, t, l, w, w, w]
    seqB = [w, l, w, w, l, w, t, w]
    ra, dda, pa = path(seqA)
    rb, ddb, pb = path(seqB)
    out["v19"] = {"เดิม": {"ลำดับ": seqA, "สะสม": ra, "ลึกสุด": -dda, "ยอด": pa, "ต่ำสุด": min(ra)},
                  "ใหม่": {"ลำดับ": seqB, "สะสม": rb, "ลึกสุด": -ddb, "ยอด": pb},
                  "จบ": ra[-1], "แพ้ติดกันสองไม้": 2 * l, "แพ้สองไม้คั่นเสมอ": 2 * l + t}

    # ── v20 · บท 18: หลักประกันขา short 20% แทน 10% ──
