    # ── v10 · บท 8: คืนที่ BTC ขึ้น 4% ──
    bA, valA = g("บัญชีมิน.beta.A"), D(1000)
    mv = D("0.04")
    out["v10"] = {"Aขึ้นเปอร์เซ็นต์": num(bA * mv * 100), "ขาA": i(valA * bA * mv), "ขาBTCมูลค่าเท่ากัน": i(-valA * mv),
                  "รวมมูลค่าเท่ากัน": i(valA * bA * mv - valA * mv), "hedgeตามbeta": i(valA * bA),
                  "ขาBTCตามbeta": i(-valA * bA * mv), "รวมตามbeta": i(0 * mv),
                  "exposure": i(valA * bA - valA), "คืนลงเดิม": i(-(valA * bA - valA) * mv)}

    # ── v11 · บท 9: ไม้บรรทัดจากช่วงที่แกว่งกว่า SD 4 ──
    m9, sd9, x9 = g("ch09.v2.คู่สอนEF.Mean"), D(2), D(11)
    out["v11"] = {"Mean": i(m9), "SDเดิม": i(sd9), "SDใหม่": i(2 * sd9), "X": i(x9),
                  "Zเดิม": num((x9 - m9) / sd9), "Zใหม่": q((x9 - m9) / (2 * sd9), 2),
                  "Xเข้าเดิม": i(m9 + 2 * sd9), "Xเข้าใหม่": i(m9 + 2 * 2 * sd9),
                  "ผิดลืมลบMean": q(x9 / (2 * sd9), 2)}

    # ── v12 · บท 10: เกณฑ์เข้มขึ้น โอกาสหลอก 1% ต่อคู่ ──
    out["v12"] = {"เดิม50": q((1 - D("0.95") ** 50) * 100, 1), "ใหม่50": q((1 - D("0.99") ** 50) * 100, 1),
                  "ใหม่20": q((1 - D("0.99") ** 20) * 100, 1), "ไม่เจอใหม่50": q(D("0.99") ** 50 * 100, 1)}

    # ── v13 · บท 11: ยี่สิบชุดแทนสิบชุด ──
    sets13 = D(20)
    a0, a1, b0, b1 = D(100), D(102), D(50), D("50.95")
    feefill = sets13 * a0 * taker                         # มูลค่าขาละ 2,000 × 0.05%
    gain13 = sets13 * (a1 - a0) - 2 * sets13 * (b1 - b0)
    out["v13"] = {"ชุด": i(sets13), "จำนวนA": i(sets13), "จำนวนB": i(-2 * sets13), "ขาA": i(sets13 * (a1 - a0)),
                  "ขาB": i(-2 * sets13 * (b1 - b0)), "กำไรจากราคา": i(gain13), "มูลค่าขา": i(sets13 * a0),
                  "ต่อfill": i(feefill), "ค่าธรรมเนียม": i(4 * feefill), "สุทธิ": i(gain13 - 4 * feefill),
                  "Xขยับ": num(gain13 / sets13), "คุ้มทุนต่อชุด": num(4 * feefill / sets13)}

    # ── v14 · บท 12: ถือได้ไม่เกิน 2 ช่วงแทน 3 ช่วง ──
    outs = [g(f"ch15.v2.สามตอนจบ.{k}") for k in range(3)]
    mix = [D(60) / 100, D(25) / 100, D(15) / 100]
    x2 = g("ch12.v2.หน้า.รายขา2.X.2")
    sets, cost = g("บัญชีมิน.คู่.ชุด"), g("ch12.v2.ต้นทุน.ไปกลับ")
    entry = g("ch12.จุดเข้า")
    net2 = sets * (entry - x2) - cost
    ev_old = sum(p * o for p, o in zip(mix, outs))
    ev_new = mix[0] * outs[0] + mix[1] * net2 + mix[2] * outs[2]
    out["v14"] = {"Xช่วง2": num(x2), "กำไรจากราคา": num(sets * (entry - x2)), "สุทธิ": num(net2),
                  "ค่าคาดหวังเดิม": num(ev_old), "ค่าคาดหวังใหม่": num(ev_new), "ลดลง": num(ev_new - ev_old),
                  "ส่วนเส้นทาง2เดิม": num(mix[1] * outs[1]), "ส่วนเส้นทาง2ใหม่": num(mix[1] * net2)}

    # ── v15 · บท 13: ถือ 8 ช่วงแทน 4 ช่วง ──
    x0 = D(2)

    def world(phi, n):
        x = q(x0 * phi ** n, 2)
        return x, num(sets * (x0 - D(str(x))), 2), num(sets * (x0 - D(str(x))) - cost, 2)
    v15 = {}
    for name, phi in (("0.80", D("0.80")), ("0.99", D("0.99"))):
        for n in (8, 10, 11):
            x, gn, nt = world(phi, n)
            v15.setdefault(name, {})[str(n)] = {"X": x, "กำไรจากราคา": gn, "สุทธิ": nt}
    v15["สุทธิ4ช่วง0.80"] = num(g("ch13.v2.ตารางคูณ.0.80.สุทธิ4ช่วง"))
    v15["สุทธิ4ช่วง0.99"] = num(g("ch13.v2.ตารางคูณ.0.99.สุทธิ4ช่วง"))
    v15["เส้นคุ้ม"] = num(x0 - cost / sets)
    n = 1
    while q(x0 * D("0.99") ** n, 2) > x0 - cost / sets:
        n += 1
    v15["ช่วงที่ต้องถือ"] = n
    v15["ครึ่งชีวิต0.99"] = i(g("ch13.ตารางphi.0.99.ครึ่งชีวิตปัด"))
    out["v15"] = v15

    # ── v16 · บท 14: เผื่อกระโดด 3 แทน 2 ──
    capP = g("บัญชีมิน.กฎ1%.ทุนรวมดอลลาร์")
