def _stats(series, nf=250):
    f = series[:nf]
    m = sum(f) / nf
    sd = math.sqrt(sum((x - m) ** 2 for x in f) / (nf - 1))
    z = [(x - m) / sd for x in series]
    zf, zt = z[:nf], z[nf:]
    share = lambda zs, k: sum(1 for v in zs if abs(v) <= k) / len(zs)  # noqa: E731
    i_max = max(range(len(zt)), key=lambda i: abs(zt[i]))
    return {"ช่วงเลือกในหนึ่งระยะ": share(zf, 1), "ช่วงเลือกในสองระยะ": share(zf, 2),
            "ช่วงทดสอบในสองระยะ": share(zt, 2), "ช่วงทดสอบzไกลสุด": zt[i_max], "ช่วงทดสอบวันไกลสุด": i_max + 1,
            "ปลายทางเปอร์เซ็นต์": (math.exp(series[-1]) - 1) * 100}


