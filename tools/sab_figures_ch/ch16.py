"""บท 16 — จากกราฟสู่คำสั่งจริง · ค่าใหม่ที่บทใช้ (ปลั๊กอินของ tools/sab_figures.py)

ทุกค่าคำนวณจาก ch16 / ch11 / ch05 / ch07 / บัญชีมิน / _สมมติฐาน ที่ sab_figures.py สร้างแล้ว — ไม่มีผลลัพธ์ลอย
- ขาเดียว: แยก +16 เป็นรายขา (A ครบ 10 · B ได้ −8 จาก −20 · ราคา 100 → 102 และ 50 → 50.5 ของ ch11)
  ส่วนที่ต่างจาก +10 = จำนวน B ที่ขาด × การขยับของ B · การกระจายเมื่อ B ขยับ −5 / −1 / +1 / +5% (เอียง 600 คูณ %)
- เส้นเวลา: เป้า · ได้จริง · มูลค่าสุทธิที่ถือ (exposure ตามมูลค่า) สี่จังหวะ
- หลักประกันขา B (กติกาข้อ 39): perp ไม่ได้เงินสดจากการขาย ต้องวางหลักประกัน 10% (กติกาสอนของเล่ม)
- บัญชีคู่ taker: ต้นทุนที่การ์ดสมมติ (0.4 + 0.6) เทียบค่าธรรมเนียม taker จริงของสามไม้
- capacity: ค่าที่บทพูดถึง (ลดจากการ์ด 6.95 → 3.87 · ถ้าขยายเป็นเส้นตรง) + ส่วนต่างราคาเฉลี่ยต่อครั้งที่กินส่วนเกินหมด
  ของบัตรใบ 1–3 (carry: ส่วนเกิน ÷ มูลค่าซื้อขายรวม · funding: ส่วนเกิน ÷ มูลค่าซื้อขาย maker · คู่: (edge − 2 taker) ÷ 2)
- netting: B ที่ต้องซื้อขายเมื่อหักกลบ vs แยกคู่ · ค่าธรรมเนียม taker
- กันชนไม่เทรด (no-trade buffer · คีย์ notradebuffer เดิมเป็น null จึงใช้คีย์ใหม่):
  กติกา = ส่งคำสั่งปรับขา B เมื่อ |เป้าใหม่ − ที่ถือ| ≥ กันชน (2 ตัว = 10% ของขา) · ต่ำกว่านั้นไม่ทำอะไร
  เป้ามาจาก h ที่คิดใหม่ทุกเดือน 🔢 (2 → 1.9 → 2.1 → 2 → 1.8 · แกว่งเองแม้เชือกไม่เปลี่ยน) × A 10 ตัว
  ต้นทุนต่อดอลลาร์ที่ซื้อขาย = taker 0.05% + ส่วนต่างราคาชั้นแรกของกระดานสมมติ 0.05%
"""

H_MONTHLY = ["2", "1.9", "2.1", "2", "1.8"]     # 🔢 สมมติเพื่อสอน: h ที่คิดใหม่ทุกเดือนจากช่วงเลือกใหม่
BUFFER_UNITS = 2                                # กันชน: ปรับเมื่อเป้าต่างจากที่ถือตั้งแต่ 2 ตัว B ขึ้นไป


def extend(data, D, q):
    c16 = data["ch16"]
    acct = data["บัญชีมิน"]
    pair = acct["คู่"]
    pA, pB = D(str(pair["A"])), D(str(pair["B"]))                  # 100 · 50
    newA = D(str(data["ch11"]["ราคาใหม่"]["A"]))                    # 102
    newB = D(str(data["ch11"]["ราคาใหม่"]["B"]))                    # 50.5
    pf = c16["ได้ขาเดียวบางส่วน"]
    nA, nB_tgt, nB_got = D(str(pf["Aได้"])), D(str(pf["Bเป้า"])), D(str(pf["Bได้"]))
    dA, dB = newA - pA, newB - pB

    # ── ขาเดียว: แยกรายขา ──
    legA = nA * dA
    legB_got, legB_tgt = nB_got * dB, nB_tgt * dB
    missing = nB_got - nB_tgt                                       # +12 (short ขาดไป 12 ตัว)
    tilt = nA * pA + nB_got * pB                                    # 1000 − 400 = 600
    one_leg = {
        "ขาA": q(legA, 0), "ขาBได้จริง": q(legB_got, 0), "ขาBเป้า": q(legB_tgt, 0),
        "Bที่ขาด": q(missing, 0), "ส่วนต่างจากที่ตั้งใจ": q(missing * dB, 0),
        "มูลค่าAที่ได้": q(nA * pA, 0), "มูลค่าBที่ได้": q(-nB_got * pB, 0), "มูลค่าBเป้า": q(-nB_tgt * pB, 0),
        "เอียง": q(tilt, 0),
    }
    # การกระจาย: ผลจริง − ผลที่ตั้งใจ = (B ที่ขาด) × การขยับของ B = เอียง 600 × % ที่ B ขยับ
    dist = []
    for pct in (-5, -1, 1, 5):
        move = pB * D(pct) / 100
        dist.append({"Bขยับเปอร์เซ็นต์": pct, "Bขยับ": q(move, 2), "ส่วนต่างจากที่ตั้งใจ": q(missing * move, 0)})
    # ทางกลับ: A ลง 2 · B ลง 0.5 (กระจกของ ch11)
    mirrorA, mirrorB = pA - dA, pB - dB
    mirror = {"A": q(mirrorA, 0), "B": q(mirrorB, 1),
              "ตั้งใจ": q(nA * (mirrorA - pA) + nB_tgt * (mirrorB - pB), 0),
              "จริง": q(nA * (mirrorA - pA) + nB_got * (mirrorB - pB), 0)}

    # ── เส้นเวลา 4 จังหวะ: เป้า · ได้จริง · มูลค่าสุทธิที่ถือ ──
    timeline = [
        {"จังหวะ": "ส่งคำสั่ง", "Aได้": 0, "Bได้": 0, "สุทธิ": 0},
        {"จังหวะ": "A ได้ครบ", "Aได้": q(nA, 0), "Bได้": 0, "สุทธิ": q(nA * pA, 0)},
        {"จังหวะ": "B ได้บางส่วน", "Aได้": q(nA, 0), "Bได้": q(nB_got, 0), "สุทธิ": q(tilt, 0)},
        {"จังหวะ": "ครบเวลารอ", "Aได้": q(nA, 0), "Bได้": q(nB_got, 0), "สุทธิ": q(tilt, 0)},
    ]

    # ── หลักประกันขา B (perp ไม่ได้เงินสด) ──
    mpct = D(str(acct["กติกาหลักประกันเปอร์เซ็นต์"]))
    legB_val = -nB_tgt * pB                                         # 1,000
    margin = legB_val * mpct / 100
    cash_need = nA * pA + margin
    onex = D(str(acct["เงินบนexchange"]))
    margin_info = {
        "มูลค่าขาB": q(legB_val, 0), "เปอร์เซ็นต์": q(mpct, 0), "หลักประกัน": q(margin, 0),
        "เงินที่ต้องใช้": q(cash_need, 0), "เหลือบนexchange": q(onex - cash_need, 0),
        "Bขึ้นเปอร์เซ็นต์": q(mpct, 0), "ขาดทุนขาBเมื่อBขึ้น": q(nB_tgt * pB * mpct / 100, 0),
        "fundingรับต่อรอบ": acct["ค่าถือคู่"]["ต่อรอบ"],
        # ทางรอด: ย้ายเงินที่เหลือบน exchange ไปเป็นหลักประกันขา B ตั้งแต่เปิด → B ขึ้นได้กี่ % ก่อนหลักประกันหมด
        "หลักประกันรวมเงินเหลือ": q(onex - nA * pA, 0),
        "Bขึ้นได้เมื่อรวมเงินเหลือเปอร์เซ็นต์": q((onex - nA * pA) / legB_val * 100, 0),
    }

    # ── ต้นทุนที่การ์ดสมมติ vs taker ──
    card = acct["การ์ด"]
    card_cost = D(str(card["ต้นทุนเข้า"])) + D(str(card["ต้นทุนออก"]))
    gross3 = [D(str(data["ch12"]["เส้นทาง"][k]["กำไรจากราคา"])) for k in ("1", "2", "3")]
    old_total = sum(D(str(data["ch12"]["เส้นทาง"][k]["สุทธิ"])) for k in ("1", "2", "3"))
    taker_cost = {
        "ต้นทุนการ์ดต่อไม้": q(card_cost, 0), "กำไรจากราคาสามไม้": [q(g, 0) for g in gross3],
        "บัญชีเดิม": q(old_total, 0), "ต่างจากเดิม": q(D(str(c16["บัญชีคู่taker"]["รวม"])) - old_total, 0),
    }

    # ── capacity: ค่าที่บทอ้าง ──
    cap = {r["ขนาดต่อขา"]: r for r in c16["capacity"]["หลัก"]["ตาราง"]}
    at1000 = D(str(cap[1000]["ต่อรอบ"]))
    fee = D(str(acct["ค่าธรรมเนียม"]["taker"]))                    # 0.05 (%)
    edge = D(str(c16["capacity"]["หลัก"]["edgeก่อนต้นทุนเปอร์เซ็นต์"]))
    ev_card = D(str(c16["capacity"]["หลัก"]["ค่าคาดหมายหลังต้นทุนการ์ด"]))
    gross_card = D(str(data["_สมมติฐาน"]["มูลค่าสองขาของการ์ด"]))
    edge_exact = (ev_card + card_cost) / gross_card * 100
    c05, c07 = data["ch05"], data["ch07"]
    maker = D(str(acct["ค่าธรรมเนียม"]["maker"]))
    funding_volume = D(str(c07["ค่าธรรมเนียมเปิดปิด"]["maker"])) / (maker / 100)
    capx = {
        "การ์ด": q(ev_card, 2), "ที่1000": q(at1000, 2),
        "ขยาย5เท่าถ้าเส้นตรง": q(at1000 * 5, 2), "ขยาย10เท่าถ้าเส้นตรง": q(at1000 * 10, 2),
        "ขยาย20เท่าถ้าเส้นตรง": q(at1000 * 20, 2),
        "จุดสูงสุดขนาด": max(cap, key=lambda s: cap[s]["ต่อรอบ"]),
        "edgeก่อนต้นทุน": q(edge, 2),
        "ทนส่วนต่างต่อครั้ง": {
            "carry": q(D(str(c05["บันได"]["ส่วนเกิน"])) / D(str(c05["มูลค่าซื้อขายรวม"])) * 100, 2),
            "funding": q(D(str(c07["บันไดเงิน"]["ส่วนเกิน"])) / funding_volume * 100, 2),
            "คู่": q((edge_exact - 2 * fee) / 2, 2),
        },
        "มูลค่าซื้อขายfunding": q(funding_volume, 0),
        # แยก 3.87 ที่ขาละ 1,000: กำไรจากราคาก่อนต้นทุน − ค่าธรรมเนียม taker (สองครั้งต่อขา) − ราคาที่เสียชั้นแรก (สองครั้งต่อขา)
        "ก่อนต้นทุนที่1000": q(edge_exact / 100 * 2 * 1000, 2),
        "ค่าธรรมเนียมที่1000": q(2 * fee / 100 * 2 * 1000, 2),
        "ราคาที่เสียที่1000": q(2 * D(str(cap[1000]["ส่วนต่างราคาเฉลี่ยเปอร์เซ็นต์"])) / 100 * 2 * 1000, 2),
    }

    # ── netting ──
    n = c16["netting"]
    gross_units = abs(D(str(n["คู่1B"]))) + abs(D(str(n["คู่2B"])))
    net_units = abs(D(str(n["สุทธิB"])))
    netting = {
        "ไม่หักกลบตัว": q(gross_units, 0), "หักกลบตัว": q(net_units, 0),
        "มูลค่าไม่หักกลบ": q(gross_units * pB, 0), "มูลค่าหักกลบ": q(net_units * pB, 0),
        "ค่าธรรมเนียมไม่หักกลบ": q(gross_units * pB * fee / 100, 2),
        "ค่าธรรมเนียมหักกลบ": q(net_units * pB * fee / 100, 2),
    }

    # ── กันชนไม่เทรด ──
    slip1 = D(str(data["_สมมติฐาน"]["กระดานสมมติ"][0][0]))          # 0.05 (%) ชั้นแรกของกระดาน
    unit_cost_pct = fee + slip1
    targets = [-nA * D(h) for h in H_MONTHLY]

    def run(buffer_units):
        held, orders, traded, worst = targets[0], 0, D(0), D(0)
        for t in targets[1:]:
            gap = abs(t - held)
            if gap >= buffer_units and gap > 0:
                orders += 1
                traded += gap
                held = t
            worst = max(worst, abs(t - held))
        return {"คำสั่ง": orders, "Bที่ซื้อขาย": q(traded, 0),
                "ต้นทุน": q(traded * pB * unit_cost_pct / 100, 2),
                "เอียงสูงสุดตัว": q(worst, 0), "เอียงสูงสุดมูลค่า": q(worst * pB, 0)}

    buffer = {
        "กติกา": "ปรับขา B เมื่อเป้าใหม่ต่างจากที่ถือตั้งแต่ 2 ตัวขึ้นไป (10% ของขา) · น้อยกว่านั้นไม่ส่งคำสั่ง",
        "hรายเดือน": [float(h) if "." in h else int(h) for h in H_MONTHLY],
        "เป้าB": [q(t, 0) for t in targets],
        "กันชนตัว": BUFFER_UNITS, "กันชนเปอร์เซ็นต์ของขา": q(D(BUFFER_UNITS) * pB / legB_val * 100, 0),
        "ต้นทุนต่อดอลลาร์เปอร์เซ็นต์": q(unit_cost_pct, 2),
        "ปรับทุกครั้ง": run(1),
        "มีกันชน": run(BUFFER_UNITS),
    }

    # ── ✍️ ──
    exA = nA * dA                                                   # ข้อ ก: B ได้ −12 จาก −20
    ex_got = D(-12)
    ex = {
        "ก": {"Bได้": q(ex_got, 0), "ผล": q(exA + ex_got * dB, 0), "เอียง": q(nA * pA + ex_got * pB, 0),
              "Bที่ขาด": q(ex_got - nB_tgt, 0)},
        "ค": {"spot": 1, "futuresได้": 0.5, "longสุทธิ": q(D(str(acct["BTC"]["spot"])) / 2, 0),
              "BTCลงเปอร์เซ็นต์": -4, "ผลจากส่วนที่เอียง": q(-D(str(acct["BTC"]["spot"])) / 2 * D(4) / 100, 0)},
    }

    return {
        "ขาเดียว": one_leg, "ขาเดียวกระจาย": dist, "ขาเดียวกลับทาง": mirror,
        "เส้นเวลา": timeline, "หลักประกันขาB": margin_info, "ต้นทุนการ์ดกับtaker": taker_cost,
        "capacityที่อ้าง": capx, "nettingเงิน": netting, "กันชนไม่เทรด": buffer, "แบบฝึกค่า": ex,
        "_claims": [
            {"id": "ch16-order-types", "ข้อความ": "แอป exchange หลายแห่งมีคำสั่งแบบตั้งรอเท่านั้น (post-only) · "
             "ได้เท่าไรเอาเท่านั้น (IOC) · ลดสถานะเท่านั้น (reduce-only) แต่ชื่อและกติกาต่างกันตามแห่ง",
             "ระดับหลักฐาน": "ตัวอย่างสอน", "แหล่ง": None, "บท": [16]},
            {"id": "ch16-thin-book", "ข้อความ": "เหรียญเล็กมีคำสั่งรอในกระดานบางกว่าเหรียญใหญ่ ขนาดที่โตขึ้นจึงได้ราคาเฉลี่ยแย่ลงเร็วกว่า",
             "ระดับหลักฐาน": "สมมติฐาน", "แหล่ง": None, "บท": [16]},
        ],
        "_แบบฝึก": [
            {"โจทย์": "A ได้ครบ 10 · B ได้ −12 จาก −20 · A 100 → 102 · B 50 → 50.5 · ผลจากราคาเท่าไร",
             "คำตอบ": float(q(exA + ex_got * dB, 0))},
            {"โจทย์": "ขยายเป็นขาละ 10,000 ได้ค่าคาดหมายต่อไม้เท่าไรตามเส้นกำไรตามขนาด",
             "คำตอบ": float(cap[10000]["ต่อรอบ"])},
            {"โจทย์": "carry 1 BTC: spot ครบ futures ได้ครึ่ง · BTC −4% ส่วนที่เอียงเสียเท่าไร",
             "คำตอบ": float(q(-D(str(acct["BTC"]["spot"])) / 2 * D(4) / 100, 0))},
        ],
    }
