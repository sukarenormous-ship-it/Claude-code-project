"""บท 18 — เอาไปต่อยอด: คู่ใหม่ ตลาดใหม่ ไอเดียใหม่ · ค่าใหม่ที่บทใช้ (ปลั๊กอินของ tools/sab_figures.py)

- บอทสามตัวของโจ้ (🔢 ตัวเลขในโพสต์สมมติ · โจ้และบอทเป็นตัวละครสมมติ)
    grid "ชนะ 90%"   : ตารางในโพสต์ ไม้ชนะเฉลี่ย +0.5% · ไม้แพ้เฉลี่ย −6% (ราคาวิ่งหลุดกรอบ ขายของค้าง)
                       → ค่าคาดหมายต่อไปกลับ · ต้องชนะกี่ % (เสีย ÷ (ได้ + เสีย)) · แพ้หนึ่งครั้งกินกำไรกี่ไม้
    funding "12% ต่อปี": ตัวเลขชั้นบนจอ — เทียบบันได funding บท 7
    AI "แม่น 70%"    : 70% คือช่วงที่ใช้สอนบอท · ช่วงหลังจากนั้น 65% (= ch18.บอทชนะ65 ของต้นฉบับ 05.08)
                       ได้ 1 เสีย 3 ต้นทุน 0.1 → ที่ 70% ก็ยังติดลบ
- payoff เท่ากัน ≠ กำไรเท่ากัน (05.03 ด้วย spot–futures): ถือ spot 100,000 vs long futures 103,000 ถึงราคาชำระ 105,000
- ตัวอย่างย้ายเต็มหนึ่งตัว: โทเคน S ที่แลกคืนเป็นเหรียญแม่ P ได้ 1 ต่อ 1 หลังรอคิว (🔢 ไม่ใช่เหรียญจริง)
    ซื้อ S 10 ตัวที่ 99.4 · short perp ของ P 10 ตัวที่ 100 · รอคิว 15 วัน แลกคืน ขาย P แล้วปิด short
    ค่าธรรมเนียม taker 4 ครั้ง · หลักประกันขา short ตามกติกาสอน 10% · ค่าถือขา short จดแยก (ตัวอย่างตั้งเป็น 0)
    → สุทธิ · ต่อทุน · ต่อปีแบบ simple · ส่วนเกินหลัง hurdle · หาง (แลกคืนถูกระงับ S ลงเหลือ 70) · รอบชดเชย
    → มือที่แย่งเชือก (ส่วนลดเหลือ 0.2%) · คิวยาวขึ้นเป็น 40 วัน
- แบบฝึก ✍️ (ก) บอทชนะ 80% ได้ 1 เสีย 5 ต้นทุน 0.1 (ค) โทเคนเดียวกัน คิว 40 วัน
"""

import math


def _bot(D, q, win, gain, loss, cost):
    p = D(win) / 100
    g, l, c = D(str(gain)), D(str(loss)), D(str(cost))
    ev = p * g - (1 - p) * l - c
    need = (l + c) / (g + l) * 100
    return {"ชนะ": win, "ได้": float(g) if g != g.to_integral() else int(g),
            "เสีย": -(float(l) if l != l.to_integral() else int(l)),
            "ต้นทุน": float(c) if c != c.to_integral() else int(c),
            "ค่าคาดหมาย": q(ev, 2), "ต้องชนะเปอร์เซ็นต์": q(need, 1),
            "100ครั้ง": {"ได้": q(p * g * 100, 0), "เสีย": q(-(1 - p) * l * 100, 0),
                         "ต้นทุน": q(-c * 100, 0), "รวม": q(ev * 100, 0)}}


def extend(data, D, q):
    acc = data["บัญชีมิน"]
    taker = D(str(acc["ค่าธรรมเนียม"]["taker"])) / 100
    hurdle = D(str(acc["hurdle"]))
    margin = D(str(acc["กติกาหลักประกันเปอร์เซ็นต์"])) / 100

    # ── บอทสามตัว ──
    gw, gg, gl = 90, D("0.5"), D("6")
    p = D(gw) / 100
    grid = {"ชนะ": gw, "ได้เปอร์เซ็นต์": 0.5, "เสียเปอร์เซ็นต์": -6,
            "ค่าคาดหมายเปอร์เซ็นต์": q(p * gg - (1 - p) * gl, 2),
            "ต้องชนะเปอร์เซ็นต์": q(gl / (gg + gl) * 100, 1),
            "แพ้หนึ่งกินไม้ชนะ": q(gl / gg, 0)}
    ai_test = data["ch18"]["บอทชนะ65"]
    ai70 = _bot(D, q, 70, ai_test["ได้"], -ai_test["เสีย"], ai_test["ต้นทุน"])
    ai = {"แม่นช่วงสอน": 70, "แม่นช่วงหลัง": ai_test["ชนะ"], "ที่70": ai70}
    funding = {"โฆษณาเปอร์เซ็นต์ต่อปี": 12,
               "เทียบบนจอบท7": data["ch07"]["บันไดfunding"]["บนจอ"],
               "เทียบส่วนเกินบท7": data["ch07"]["บันไดfunding"]["ส่วนเกินเปอร์เซ็นต์"]}

    # ── payoff เท่ากัน ≠ กำไรเท่ากัน ──
    btc = acc["BTC"]
    s0, f0, st = D(btc["spot"]), D(btc["futures"]), D(btc["ราคาชำระ"])
    payoff = {"spot": q(st - s0, 0), "futures": q(st - f0, 0), "ต่าง": q(f0 - s0, 0),
              "ราคาขยับเท่ากันต่อ1000": 1000}

    # ── โทเคนแลกคืนกับเหรียญแม่ ──
    P, S, n, days = D("100"), D("99.4"), D("10"), 15
    gain = n * (P - S)
    fees = taker * (n * S + n * P + n * P + n * P)        # ซื้อ S · short P · ขาย P ที่แลกได้ · ซื้อคืน short
    net = gain - fees
    cap = n * S + margin * n * P
    per = net / cap * 100
    ann = per * 365 / days
    tail_price = D("70")
    tail = n * (tail_price - S)
    crowd_S = D("99.8")
    crowd_gain = n * (P - crowd_S)
    crowd_fees = taker * (n * crowd_S + 3 * n * P)
    long_q = 40
    ann_long = per * 365 / long_q
    token = {
        "ราคาเหรียญแม่": 100, "ราคาโทเคน": 99.4, "จำนวน": 10, "คิววัน": days,
        "ส่วนลดเปอร์เซ็นต์": q((P - S) / P * 100, 1), "กำไรจากราคา": q(gain, 0),
        "ค่าธรรมเนียม": q(fees, 0), "ค่าธรรมเนียมทศนิยม": q(fees, 2), "สุทธิ": q(net, 0),
        "ทุนขาซื้อ": q(n * S, 0), "หลักประกันขาshort": q(margin * n * P, 0), "ทุน": q(cap, 0),
        "ต่อทุนเปอร์เซ็นต์": q(per, 2), "ต่อปีเปอร์เซ็นต์": q(ann, 2), "ส่วนเกินเปอร์เซ็นต์": q(ann - hurdle, 2),
        "เทียบcarry": data["ch05"]["บันได"]["ส่วนเกินเปอร์เซ็นต์"],
        "หาง": {"ราคาโทเคน": 70, "ขาดทุนจากราคา": q(tail, 0),
                "รอบชดเชย": int(math.ceil(float(-tail / net.quantize(D('1')))))},
        "แย่ง": {"ราคาโทเคน": 99.8, "ส่วนลดเปอร์เซ็นต์": q((P - crowd_S) / P * 100, 1),
                 "กำไรจากราคา": q(crowd_gain, 0), "สุทธิ": q(crowd_gain - crowd_fees, 0)},
        "คิวยาว": {"คิววัน": long_q, "ต่อปีเปอร์เซ็นต์": q(ann_long, 2),
                   "ส่วนเกินเปอร์เซ็นต์": q(ann_long - hurdle, 2)},
        "ค่าถือขาshort": 0,
    }

    # ── แบบฝึก ──
    ex_a = _bot(D, q, 80, 1, 5, D("0.1"))
    ex = {"ก": ex_a}

    return {
        "บอท": {"grid": grid, "funding": funding, "AI": ai},
        "payoffเท่ากัน": payoff,
        "โทเคน": token,
        "แบบฝึกค่า": ex,
        "_แบบฝึก": [
            {"โจทย์": "บอทชนะ 80% ได้ 1 เสีย 5 ต้นทุน 0.1 ต่อครั้ง ค่าคาดหมายต่อครั้ง", "คำตอบ": float(ex_a["ค่าคาดหมาย"])},
            {"โจทย์": "เพื่อนเทรด funding บนกระดาษ 30 วันได้บวก จะขึ้นขนาดปกติ — ตัดสินระดับในใบตัดสินรับงาน"},
            {"โจทย์": "โทเคนแลกคืนชุดเดียวกัน แต่คิว 40 วัน ส่วนเกินหลัง hurdle ต่อปี (%)",
             "คำตอบ": float(token["คิวยาว"]["ส่วนเกินเปอร์เซ็นต์"])},
        ],
    }
