"""บท 1 — ค่าผ่านทางสองขา และนิ้วที่จับเชือก · ค่าใหม่ที่บทพิมพ์แต่ยังไม่มีใน ch01 เดิม

ทุกค่าคำนวณจาก บัญชีมิน (ค่าธรรมเนียม taker 0.05% · maker 0.02% · มินใน nq 0.1% · bid/ask · สเกล 0.01)
+ ch01/ch00 เดิม หรือจากตัวเลขโจทย์ที่ประกาศในบท (🔢 สมมติเพื่อสอน)
หมายเหตุการปัด: ต้นทุนสองขาคิดที่ราคา 100,000 ทั้งสองขา (เลขกลมแบบ ch01.ต้นทุนไปกลับ.สองขา เดิม)
"""


def extend(data, D, q):
    m, c1 = data["บัญชีมิน"], data["ch01"]
    btc = m["BTC"]
    px = D(btc["spot"])
    bid, ask = D(btc["bid"]), D(btc["ask"])
    spread = ask - bid                                              # 20
    fee = m["ค่าธรรมเนียม"]
    taker, maker, nq = (D(str(fee[k])) / 100 for k in ("taker", "maker", "มินในnq"))
    basis = D(btc["basis"])
    scale = D(str(m["สเกล"]))

    def mini(x):
        v = D(str(x)) * scale
        return q(v, 0) if v == v.to_integral() else q(v, 2)

    def level(rate, cross_spread=True):
        """ไปกลับหนึ่งขา (เปิดแล้วปิด) ที่ราคา 100,000 · taker ข้ามส่วนต่าง · maker (ถ้าได้ราคาที่ตั้งรอทั้งสองครั้ง) ไม่ข้าม"""
        sp = spread if cross_spread else D(0)
        f = 2 * rate * px
        one = sp + f
        two = 2 * one
        return {"ส่วนต่าง": q(-sp, 0), "ค่าธรรมเนียมต่อข้าง": q(-rate * px, 0), "ค่าธรรมเนียมไปกลับ": q(-f, 0),
                "ไปกลับหนึ่งขา": q(-one, 0), "เปอร์เซ็นต์": q(one / px * 100, 2),
                "ส่วนต่างสองขา": q(-2 * sp, 0), "ค่าธรรมเนียมสองขา": q(-2 * f, 0),
                "สองขา": q(-two, 0), "3000ลบสองขา": q(basis - two, 0),
                "ส่วนของbasisเปอร์เซ็นต์": q(two / basis * 100, 2)}

    lv = {"taker": level(taker), "maker": level(maker, cross_spread=False), "มินในnq": level(nq)}
    # ต้องตรงกับ ch01 เดิม (สร้างใน sab_figures.py) — กันสองแหล่งพูดไม่ตรงกัน
    assert lv["taker"]["สองขา"] == c1["ต้นทุนไปกลับ"]["สองขา"], "taker สองขาไม่ตรง ch01.ต้นทุนไปกลับ"
    assert lv["มินในnq"]["สองขา"] == c1["ต้นทุนไปกลับที่0.1"]["สองขา"], "0.1% สองขาไม่ตรง ch01.ต้นทุนไปกลับที่0.1"

    # leverage: หลักประกัน 1,000 ถือ 10,000 · ราคาสวนกี่ % หลักประกันหมด = 100 ÷ เท่า
    lev = {}
    for x in (2, 5, 10, 20):
        lev[str(x)] = {"เท่า": x, "หลักประกันต่อ10000": q(D(10000) / x, 0), "สวนแล้วหมดเปอร์เซ็นต์": q(D(100) / x, 0)}
    rule = D(str(m["กติกาหลักประกันเปอร์เซ็นต์"]))
    fut = D(btc["futures"])

    # ✍️ ข้อ 1 (00.07 ข้อ 2–3 ดัดแปลง): เหรียญ 50,000 · bid 49,995 · ask 50,005 · taker · หลักประกัน 2,000 ที่ 5 เท่า สวน 4%
    e_px, e_bid, e_ask = D(50000), D(49995), D(50005)
    e_sp = e_ask - e_bid
    e_fee = 2 * taker * e_px
    e_one = e_sp + e_fee
    e_marg, e_lev, e_move = D(2000), D(5), D(4)
    e_pos = e_marg * e_lev
    e_loss = e_pos * e_move / 100

    # ✍️ ข้อ 2: ตั้งรอทั้งสองขา ได้ซื้อ spot ที่ bid 99,990 แต่ขา short futures ยังไม่มีคนชน · ราคาลง 500
    drop = D(500)
    saved = D(-lv["taker"]["สองขา"]) - D(-lv["maker"]["สองขา"])

    # ✍️ ข้อ 3 (ถ่ายโอน): สัญญาใกล้ของบัตรตลาดมิน basis 1,000
    near = D(data["ch00"]["บัตรตลาดมิน"]["basisใกล้"])
    t2, n2 = D(-lv["taker"]["สองขา"]), D(-lv["มินในnq"]["สองขา"])

    trial = D(data["เรื่อง"]["part1"]["close"]["บัญชีทดลอง"])
    out = {
        "สามระดับ": lv,
        "ประหยัดถ้าmakerครบสองขา": q(saved, 0),
        "ประหยัดเป็นเปอร์เซ็นต์ของราคา": q(saved / px * 100, 2),
        "leverageตาราง": lev,
        "ขาfuturesของcarry": {"กติกาเปอร์เซ็นต์": q(rule, 0), "เท่า": q(100 / rule, 0),
                               "หลักประกัน": q(rule / 100 * fut, 0)},
        "ของมิน": {
            "ส่วนต่าง": mini(-spread), "ค่าธรรมเนียม": mini(lv["taker"]["ค่าธรรมเนียมไปกลับ"]),
            "รวม": mini(lv["taker"]["ไปกลับหนึ่งขา"]), "สองขา": mini(lv["taker"]["สองขา"]),
            "basis": mini(basis), "3000ลบสองขา": mini(lv["taker"]["3000ลบสองขา"]),
            "เงินบนexchange": q(D(m["เงินบนexchange"]), 0),
            "ยอดหลังทดลอง": q(D(m["เงินบนexchange"]) + trial * scale, 2),
            "บัญชีทดลอง": mini(trial),
            "จำนวนBTC": q(scale, 2),
        },
        "_claims": [
            {"id": "ch01-maker-cheaper",
             "ข้อความ": "หลาย exchange คิดค่าธรรมเนียมคำสั่งตั้งรอ (maker) ต่ำกว่าคำสั่งซื้อทันที (taker) และมีระดับค่าธรรมเนียมตามปริมาณ"
                        "ซื้อขาย · ส่วนลดนี้แลกกับความไม่แน่นอนว่าคำสั่งจะได้ซื้อขายครบหรือไม่ — อัตราจริงต้องจดจากตารางของ exchange ที่ใช้",
             "ระดับหลักฐาน": "สมมติฐาน", "แหล่ง": None, "บท": [1, 7]},
            {"id": "ch01-liquidity-provider",
             "ข้อความ": "ผู้ดูแลสภาพคล่อง (market maker) วางคำสั่งตั้งรอทั้งสองฝั่งเพื่อรับส่วนต่างราคาซื้อ-ขายจากคนที่ต้องการซื้อขายทันที · "
                        "ความเสี่ยงของเขาคือได้ขาเดียวเมื่ออีกฝั่งรู้ข่าวก่อนหรือมีแรงขายต่อเนื่อง (adverse selection) และของที่ค้าง (inventory) · "
                        "ส่วนต่างจึงมักกว้างขึ้นเมื่อตลาดผันผวน",
             "ระดับหลักฐาน": "สมมติฐาน", "แหล่ง": None, "บท": [1, 18]},
        ],
        "_แบบฝึก": [
            {"โจทย์": "เหรียญ 50,000 · bid 49,995 ask 50,005 · taker 0.05% → ไปกลับหนึ่งขา (เงิน · %) และสองขา · "
                      "หลักประกัน 2,000 ที่ 5 เท่า ราคาสวน 4% เสียเท่าไร กี่ % ของหลักประกัน",
             "ราคา": q(e_px, 0), "bid": q(e_bid, 0), "ask": q(e_ask, 0),
             "ส่วนต่าง": q(e_sp, 0), "ค่าธรรมเนียมไปกลับ": q(e_fee, 0), "ไปกลับหนึ่งขา": q(e_one, 0),
             "เปอร์เซ็นต์": q(e_one / e_px * 100, 2), "สองขา": q(2 * e_one, 0),
             "หลักประกัน": q(e_marg, 0), "เท่า": q(e_lev, 0), "ขนาดสถานะ": q(e_pos, 0), "สวนเปอร์เซ็นต์": q(e_move, 0),
             "เสีย": q(-e_loss, 0), "ส่วนของหลักประกันเปอร์เซ็นต์": q(e_loss / e_marg * 100, 0),
             "หมดเมื่อสวนเปอร์เซ็นต์": q(D(100) / e_lev, 0),
             "คำตอบ": [q(e_one, 0), q(2 * e_one, 0), q(e_loss, 0)]},
            {"โจทย์": "ตั้งรอทั้งสองขา ได้ซื้อ spot ที่ 99,990 แต่ขา short futures ยังไม่ได้ · BTC ลง 500 → เสียบนขาที่ค้างเท่าไร "
                      "เทียบค่าธรรมเนียมที่ประหยัดได้",
             "ซื้อได้ที่": q(bid, 0), "ราคาลง": q(drop, 0), "ราคาหลังลง": q(bid - drop, 0), "เสียขาค้าง": q(-drop, 0),
             "ประหยัดได้": q(saved, 0), "สุทธิเทียบtaker": q(saved - drop, 0), "คำตอบ": q(drop, 0)},
            {"โจทย์": "สัญญาใกล้ basis 1,000 · ค่าผ่านทางสองขาที่ taker 0.05% และที่ 0.1% เหลือเท่าไร กินกี่ %",
             "basis": q(near, 0), "เหลือtaker": q(near - t2, 0), "กินtakerเปอร์เซ็นต์": q(t2 / near * 100, 0),
             "เหลือ0.1": q(near - n2, 0), "กิน0.1เปอร์เซ็นต์": q(n2 / near * 100, 0),
             "คำตอบ": [q(near - t2, 0), q(near - n2, 0)]},
        ],
    }
    return out
