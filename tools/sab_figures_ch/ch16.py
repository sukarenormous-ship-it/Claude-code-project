def _v2(data, D, q):
    """บท 16 ด้วยฐานต้นทุนเดียว (ch11.v2) · เดินกระดานให้คิดตามได้ (รายงาน C §2.6 ข้อ 15)

    - กระทบยอด: การ์ดใช้ต้นทุน 2 ต่อไม้ (taker คิดที่ขาละ 1,000) · แอปคิด taker จากมูลค่าจริงสี่ fill → 2.01 / 2.02 / 2.03
    - เส้นกำไรตามขนาด (ใหม่ · แทนเส้นเดิมที่ซ่อนตัวคูณ 2,000 ÷ 2,021 และค่าธรรมเนียมแยก):
        ขาละ s = s ÷ 100 ชุด = (s ÷ 1,000) เท่าของ 10 ชุด
        ค่าคาดหมายตามการ์ด (หลังค่าธรรมเนียม taker แล้ว) = 5.95 × s ÷ 1,000
        ราคาที่เสียจากกระดาน ต่อ fill = เดินกระดานสมมติ (ชั้นละ % ห่างราคากลาง × มูลค่าที่กินในชั้นนั้น)
        หนึ่งไม้มี 4 fill (เข้า A · เข้า B · ออก A · ออก B) และสมมติว่าทุก fill กินกระดานลึกเท่ากัน
        ค่าคาดหมายต่อไม้ = 5.95 × s ÷ 1,000 − 4 × ราคาที่เสียต่อ fill
    """
    acct = data["บัญชีมิน"]
    v12 = data["ch12"]["v2"]
    cost = D(str(data["ch11"]["v2"]["ต้นทุน"]["ไปกลับ"]))
    rate = D(str(acct["ค่าธรรมเนียม"]["taker"])) / 100
    sets = D(str(acct["คู่"]["ชุด"]))
    B = D(str(acct["คู่"]["B"]))
    e = D(str(data["ch12"]["จุดเข้า"]))
    rec = []
    for k in ("1", "2", "3"):
        xo = D(str(v12["เส้นทาง"][k]["Xออก"]))
        vals = [sets * (100 + e), -(-20) * B, sets * (100 + xo), 20 * B]      # A = 100 + X · B = 50
        fee = rate * sum(vals)
        gross = D(str(v12["เส้นทาง"][k]["กำไรจากราคา"]))
        rec.append({"มูลค่าfill": [q(v, 0) for v in vals], "มูลค่ารวม": q(sum(vals), 0), "takerจริง": q(fee, 2),
                    "กำไรจากราคา": q(gross, 0), "สุทธิการ์ด": q(gross - cost, 0), "สุทธิจริง": q(gross - fee, 2)})
    recon = {"ต้นทุนการ์ด": q(cost, 0), "ไม้": rec,
             "รวมการ์ด": q(sum(D(str(r["สุทธิการ์ด"])) for r in rec), 0),
             "รวมจริง": q(sum(D(str(r["สุทธิจริง"])) for r in rec), 2),
             "ส่วนต่าง": q(sum(D(str(r["สุทธิจริง"])) for r in rec) - sum(D(str(r["สุทธิการ์ด"])) for r in rec), 2),
             "ถ้าใช้maker": {"อัตราเปอร์เซ็นต์": acct["ค่าธรรมเนียม"]["maker"],
                             "ต่อไม้": q(D(str(acct["ค่าธรรมเนียม"]["maker"])) / 100 * 4 * 1000, 1),
                             "รวมสามไม้": q(sum(D(str(r["กำไรจากราคา"])) for r in rec)
                                           - 3 * D(str(acct["ค่าธรรมเนียม"]["maker"])) / 100 * 4 * 1000, 1)}}
    assert recon["รวมการ์ด"] == data["ch16"]["บัญชีคู่taker"]["รวม"], "บัญชีคู่ v2 ต้องเท่ากับบัญชี taker เดิมของบท 16"

    book = [(D(str(p)) / 100, D(str(v))) for p, v in data["_สมมติฐาน"]["กระดานสมมติ"]]
    ev_card = {name: D(str(v12["สัดส่วนตอนจบ"][name]["ค่าคาดหมาย"])) for name in ("หลัก", "เทียบ")}

    def walk(size):
        rem, cost_, layers = D(size), D(0), []
        for p, qty in book:
            take = min(rem, qty)
            if take <= 0:
                break
            cost_ += take * p
            layers.append({"ห่างเปอร์เซ็นต์": q(p * 100, 2), "กิน": q(take, 0), "เสีย": q(take * p, 2)})
            rem -= take
        assert rem <= 0, "กระดานสมมติไม่พอ"
        return cost_, layers

    rows = []
    for size in (500, 1000, 2000, 3000, 5000, 7500, 10000, 20000):
        slip, layers = walk(size)
        scale = D(size) / 1000
        row = {"ขนาดต่อขา": size, "ชุด": q(D(size) / 100, 0), "เท่าของ10ชุด": q(scale, 1), "ชั้นที่กิน": layers,
               "เสียต่อfill": q(slip, 2), "เสียเฉลี่ยเปอร์เซ็นต์": q(slip / size * 100, 3),
               "เสียสี่fill": q(4 * slip, 2)}
        for name in ("หลัก", "เทียบ"):
            row[f"การ์ด_{name}"] = q(ev_card[name] * scale, 2)
            row[f"ต่อไม้_{name}"] = q(ev_card[name] * scale - 4 * slip, 2)
        rows.append(row)
    best = max(rows, key=lambda r: r["ต่อไม้_หลัก"])
    at = {r["ขนาดต่อขา"]: r for r in rows}
    cap = {"ตาราง": rows, "สูงสุดที่": best["ขนาดต่อขา"], "สูงสุด": best["ต่อไม้_หลัก"],
           "ขนาดต่อขา": [1000, 5000, 10000, 20000], "ต่อรอบ": [at[s]["ต่อไม้_หลัก"] for s in (1000, 5000, 10000, 20000)],
           "ค่าคาดหมายการ์ด": q(ev_card["หลัก"], 2),
           "ขยาย20เท่าถ้าเส้นตรง": q(D(str(at[1000]["ต่อไม้_หลัก"])) * 20, 1),
           "ขยาย10เท่าถ้าเส้นตรง": q(D(str(at[1000]["ต่อไม้_หลัก"])) * 10, 1),
           "ตัวอย่างเดิน5000": {"ชุด": 50, "การ์ด": at[5000]["การ์ด_หลัก"], "เสียต่อfill": at[5000]["เสียต่อfill"],
                               "เสียสี่fill": at[5000]["เสียสี่fill"], "ต่อไม้": at[5000]["ต่อไม้_หลัก"]},
           "เทียบติดลบทุกขนาด": all(r["ต่อไม้_เทียบ"] < 0 for r in rows),
           "กติกา": "ค่าคาดหมายต่อไม้ = 5.95 × ขาละ ÷ 1,000 − 4 × ราคาที่เสียต่อ fill จากกระดานสมมติ"}
    return {"กระทบยอด": recon, "capacity": cap}


def _ints(o):
    """ค่า float ที่เป็นจำนวนเต็ม → int (พิมพ์ไม่มี .0 · คู่มือข้อ 33)"""
    if isinstance(o, dict):
        return {k: _ints(v) for k, v in o.items()}
    if isinstance(o, list):
        return [_ints(v) for v in o]
    if isinstance(o, float) and o == int(o):
        return int(o)
    return o


def extend(data, D, q):
    c16 = data["ch16"]
    acct = data["บัญชีมิน"]
    pair = acct["คู่"]
    pA, pB = D(str(pair["A"])), D(str(pair["B"]))                  # 100 · 50
    newA = D(str(data["ch11"]["ราคาใหม่"]["A"]))                    # 102
