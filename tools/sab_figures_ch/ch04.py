"""บท 4 — คืนที่ราคาขึ้น 10% · ค่าที่บทพิมพ์แต่ยังไม่มีใน JSON หลัก

ทุกค่าคำนวณจาก บัญชีมิน + ch04 เดิม (กติกาหลักประกันสอน 10% ของราคา futures · ชำระสิ้นวัน)
"""


def extend(data, D, q):
    m, c = data["บัญชีมิน"], data["ch04"]
    rate = D(str(m["กติกาหลักประกันเปอร์เซ็นต์"])) / 100          # 0.10
    mult = 1 + rate                                                  # 1.1 = จ่ายขาดทุน 1 + หลักประกันเพิ่ม 0.1
    s0, f0 = D(m["BTC"]["spot"]), D(m["BTC"]["futures"])
    s1, f1 = D(c["คืนวันที่9"]["spot"]), D(c["คืนวันที่9"]["futures"])
    settle = D(m["BTC"]["ราคาชำระ"])
    scale = D(str(m["สเกล"]))

    def free_cash(cap, r=rate):
        return D(cap) - s0 - r * f0

    def buffer_money(cap, r=rate):
        return free_cash(cap, r) / (1 + r)

    # ทุน 150,000 (✍️ ข้อ 1)
    free150 = free_cash(150000)
    # หลังคืนวันที่ 9 (ทุน 125,000) เหลือเงินสดอิสระ 3,480
    after1 = D(c["เงินสดอิสระหลังโอน"])
    # ✍️ ข้อ 2: วันถัดไปราคา futures ขึ้นอีก 3% จาก 113,200
    rise2_pct = D(3)
    rise2 = f1 * rise2_pct / 100
    top2 = mult * rise2
    free150_after1 = free150 - D(c["ต้องโอน"])
    # ✍️ ข้อ 3 (ถ่ายโอน): exchange ที่กติกาหลักประกัน 20% · ทุน 125,000 เท่าเดิม
    r20 = D("0.20")
    m20_init = r20 * f0
    free20 = free_cash(125000, r20)
    buf20 = buffer_money(125000, r20)

    # วันหมดอายุ (แถวสุดท้ายของตาราง 6 แถว)
    rows = c["ตารางบัญชี"]
    expiry_settle = f1 - settle                                       # ขา short futures ได้ 8,200
    expiry_spot = settle - s1                                         # spot −5,000

    def mini(x):
        v = D(str(x)) * scale
        return q(v, 0) if v == v.to_integral() else q(v, 2)

    out = {
        "ตัวคูณหลักประกัน": q(mult, 1),
        "กำไรspotคืนวันที่9": q(s1 - s0, 0),
        "basisคืนวันที่9": q(f1 - s1, 0),
        "futuresขึ้นเปอร์เซ็นต์คืนวันที่9": q((f1 - f0) / f0 * 100, 1),
        "กันชนเงินปัด": {"125000": q(buffer_money(125000), 0), "120000": q(buffer_money(120000), 0),
                         "150000": q(buffer_money(150000), 0)},
        "เงินสดอิสระทุน150000": q(free150, 0),
        "หลังวันแรกรับได้อีกเงิน": q(after1 / mult, 2),
        "วันหมดอายุ": {"spotเปลี่ยน": q(expiry_spot, 0), "ชำระ": q(expiry_settle, 0),
                       "equityเปลี่ยน": q(D(rows[5]["equity"]) - D(rows[4]["equity"]), 0)},
        "ของมิน": {
            "เงินบนexchange": mini(m["ทุนภาค1"]["รวม"]),
            "เงินสดอิสระก่อน": mini(m["ทุนภาค1"]["เงินสดอิสระ"]),
            "ซื้อspot": mini(s0),
            "หลักประกันเริ่ม": mini(m["ทุนภาค1"]["หลักประกัน"]),
            "ต้องโอน": mini(c["ต้องโอน"]),
            "หลักประกันหลังชำระ": mini(c["หลักประกันหลังชำระ"]),
            "หลักประกันหลังโอน": mini(c["หลักประกันที่ต้องมี"]),
            "มูลค่าspot": mini(s1),
            "เงินสดอิสระหลังโอน": mini(after1),
            "equity": mini(c["equity"]),
            "equity_เปลี่ยน": mini(c["equity_เปลี่ยน"]),
            "บัญชีทดลอง": mini(data["เรื่อง"]["part4"]["close"]["บัญชีทดลอง"]),
            "กันชนเงิน": mini(buffer_money(125000)),
        },
        # ต้นหลังขา futures ถูกบังคับปิดที่ 113,200 (ยังไม่รวมค่าปรับการบังคับปิด)
        "ต้นหลังถูกปิด": {
            "ขาดทุนรับรู้": q(-(f1 - f0), 0),
            "เงินสด": q(D(c["ต้นเงินสดอิสระ"]) + D(c["หลักประกันหลังชำระ"]), 0),
            "ถ้าราคากลับ100000": q(D(c["ต้นเงินสดอิสระ"]) + D(c["หลักประกันหลังชำระ"]) + s0, 0),
            "เสียถ้าราคากลับ": q(D(c["ต้นเงินสดอิสระ"]) + D(c["หลักประกันหลังชำระ"]) + s0 - D(c["ทุนของต้น"]), 0),
            "ถ้ารอดถึงวันหมดอายุ": q(D(c["ทุนของต้น"]) + (f0 - s0), 0),
        },
        # 🔎 ถ้าวางเงินสดทั้งก้อนไว้ในบัญชีหลักประกันตั้งแต่แรก (กระเป๋าเดียว)
        "ถ้าวางทั้งก้อน": {
            "บัญชีหลักประกัน": q(D(m["ทุนภาค1"]["หลักประกัน"]) + D(m["ทุนภาค1"]["เงินสดอิสระ"]), 0),
            "หลังชำระ": q(D(m["ทุนภาค1"]["หลักประกัน"]) + D(m["ทุนภาค1"]["เงินสดอิสระ"]) - (f1 - f0), 0),
            "ต้องมี": q(rate * f1, 0),
        },
        "กติกา20": {"เปอร์เซ็นต์": 20, "ตัวคูณ": q(1 + r20, 1), "หลักประกันเริ่ม": q(m20_init, 0),
                    "เงินสดอิสระ": q(free20, 0), "กันชนเงิน": q(buf20, 2), "กันชน": q(buf20 / f0 * 100, 2)},
        "_claims": [
            {"id": "ch04-mark-continuous",
             "ข้อความ": "exchange คริปโตหลายแห่งประเมินหลักประกันตามราคา mark ต่อเนื่องและบังคับปิดเมื่อต่ำกว่าระดับรักษา "
                        "(maintenance) แทนการชำระสิ้นวัน · ราคา mark คำนวณจากดัชนีของ exchange นั้น — รายละเอียดต้องอ่านจากเอกสารสัญญา",
             "ระดับหลักฐาน": "สมมติฐาน", "แหล่ง": None, "บท": [4]},
        ],
        "_แบบฝึก": [
            {"โจทย์": "ทุน 150,000 กติกาเดิม → เงินสดอิสระ ÷ 1.1 → กันชนกี่ % ของ 103,000",
             "ทุน": 150000, "เงินสดอิสระ": q(free150, 0), "กันชนเงิน": q(buffer_money(150000), 0),
             "กันชน": c["กันชน"]["150000"], "คำตอบ": c["กันชน"]["150000"]},
            {"โจทย์": "ทุน 125,000 หลังคืนวันที่ 9 ราคา futures ขึ้นอีก 3% จาก 113,200 → ต้องโอนเท่าไร ขาดเท่าไร",
             "ทุน": 125000, "ขึ้นวันที่สอง": int(rise2_pct), "futuresขึ้นเป็นเงิน": q(rise2, 0),
             "ต้องโอนวันที่สอง": q(top2, 1), "เงินสดอิสระหลังวันแรก": q(after1, 0),
             "ขาด": q(top2 - after1, 1), "ทุน150000เงินสดอิสระหลังวันแรก": q(free150_after1, 0),
             "ทุน150000ขาด": q(max(D(0), top2 - free150_after1), 1),
             "คำตอบ": [q(top2, 1), q(top2 - after1, 1)]},
            {"โจทย์": "ย้ายไป exchange ที่กติกาหลักประกัน 20% ทุน 125,000 เท่าเดิม → เงินสดอิสระ และกันชนกี่ %",
             "หลักประกันเริ่ม": q(m20_init, 0), "เงินสดอิสระ": q(free20, 0), "ตัวคูณ": q(1 + r20, 1),
             "กันชนเงิน": q(buf20, 2), "คำตอบ": [q(free20, 0), q(buf20 / f0 * 100, 2)]},
        ],
    }
    return out
