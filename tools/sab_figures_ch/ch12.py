"""บท 12 — กฎก่อนกด: สามตอนจบที่ซ้อมไว้ · ค่าใหม่ที่บทใช้ (ปลั๊กอินของ tools/sab_figures.py)

ทุกค่าคำนวณจาก ch12 / บัญชีมิน ที่ sab_figures.py สร้างแล้ว (การ์ด · คู่ A–B · กฎ 1%) — ไม่มีตัวเลขผลลัพธ์ลอย
- รายขา: ตะกร้า X = A − 2B ที่ B = 50 คงที่ → A = X + 2 × 50 · short X 10 ชุด = short A 10 / long B 20
- ชนะ37: นับไม้ให้เห็นว่า 21 ไม้ชนะ × 16 = 16 ไม้แพ้ × 21 (อัตราชนะที่ต้องได้ 21 ÷ 37)
- ค่าคาดหมายต่อ 100 ไม้ จากสัดส่วนตอนจบ (หลัก 60/25/15 · เทียบ 45/20/35)
- แถบผล 20 ไม้ (ลำดับตรึงเพื่อสอน ไม่ใช่ผลสุ่ม) ของสองโลก
- dist: โอกาสที่สองไม้แรกไม่ชนงบเลย ในสองโลก
- ค่าถือขา short: กำไรของไม้ทนค่าถือ 0.1 ต่อรอบได้กี่รอบ · หนึ่งช่วง = 3 รอบ (บัญชีมิน.ค่าถือคู่.รอบต่อช่วง)
  ผลหลังค่าถือต่อเส้นทางอยู่ใน ch12.เส้นทาง.N.ค่าถือ / สุทธิหลังค่าถือ (sab_figures.py) · ที่นี่เพิ่มกรณี funding ติดลบเท่ากัน
  และยอดสองไม้จริงของมินหลังค่าถือ (📒)
- กฎ 1%: ถ้าเจอกระโดดแบบเส้นทาง 3 ต้องลดเหลือกี่ชุดจึงไม่เกินเพดานต่อไม้
"""


def _paths_legs(data, D, q):
    pair = data["บัญชีมิน"]["คู่"]
    h, B = D(str(pair["h"])), D(str(pair["B"]))
    nA = D(str(pair["จำนวนA"]))          # 10 (ฝั่ง long X) → short X ถือ A −10 · B +20
    nB = D(str(pair["จำนวนB"]))          # −20
    out = {}
    for k in ("1", "3"):
        xs = [D(str(x)) for x in data["ch12"]["เส้นทาง"][k]["X"][1:]]     # ตั้งแต่จุดเข้า
        A = [x + h * B for x in xs]
        legA = [q(-nA * (a - A[0]), 0) for a in A]                          # short A 10
        legB = [q(-nB * (B - B), 0) for _ in A]                             # long B 20 · B ไม่ขยับ
        out[k] = {"A": [q(a, 1) for a in A], "B": q(B, 0), "ขาA": legA, "ขาB": legB,
                  "ถือA": q(-nA, 0), "ถือB": q(-nB, 0)}
    return out


def _strip(mix, outcomes, n=20):
    """ลำดับ 20 ไม้แบบตรึง: กระจายไม้เสียให้ห่างกันเท่า ๆ กัน แล้วแทรกไม้ครบเวลา — เพื่อสอน ไม่ใช่สุ่ม"""
    counts = [round(n * p / 100) for p in mix]
    counts[0] = n - counts[1] - counts[2]
    seq = [outcomes[0]] * n
    lose_at = [int((i + 0.5) * n / counts[2]) for i in range(counts[2])] if counts[2] else []
    for i in lose_at:
        seq[i] = outcomes[2]
    free = [i for i in range(n) if i not in lose_at]
    step = len(free) / counts[1] if counts[1] else 0
    for j in range(counts[1]):
        seq[free[int(j * step + step / 2)]] = outcomes[1]
    return counts, seq


def extend(data, D, q):
    c = data["ch12"]
    acct = data["บัญชีมิน"]
    card = acct["การ์ด"]
    res = [c["เส้นทาง"][k]["สุทธิ"] for k in ("1", "2", "3")]           # +16 / +2 / −21
    win, _, lose = res
    cost = D(str(card["ต้นทุนเข้า"])) + D(str(card["ต้นทุนออก"]))
    sets = D(str(acct["คู่"]["ชุด"]))

    # อัตราชนะที่ต้องได้ ด้วยการนับ: 37 ไม้ · ชนะ 21 × 16 = แพ้ 16 × 21
    n37 = win - lose
    count37 = {"ไม้": n37, "ชนะ": -lose, "แพ้": win, "ได้รวม": -lose * win, "เสียรวม": win * lose}

    # ค่าคาดหมายจากสัดส่วนตอนจบ ต่อ 100 ไม้ และแยกพจน์ต่อไม้
    ev = {}
    for name in ("หลัก", "เทียบ"):
        mix = c["สัดส่วนตอนจบ"][name]["สัดส่วน"]
        money = [m * r for m, r in zip(mix, res)]
        ev[name] = {"ไม้": mix, "เงิน100ไม้": money, "รวม100ไม้": sum(money),
                    "ส่วนต่อไม้": [q(D(m) * D(r) / 100, 2) for m, r in zip(mix, res)],
                    "ต่อไม้": q(D(sum(money)) / 100, 2)}

    # แถบผล 20 ไม้ของสองโลก
    strip = {}
    for name in ("หลัก", "เทียบ"):
        counts, seq = _strip(c["สัดส่วนตอนจบ"][name]["สัดส่วน"], res)
        strip[name] = {"จำนวน": counts, "ลำดับ": seq, "รวม": sum(seq)}

    # dist: สองไม้แรกไม่ชนงบเลย
    no_hit = {name: q((1 - D(c["สัดส่วนตอนจบ"][name]["สัดส่วน"][2]) / 100) ** 2 * 100, 2)
              for name in ("หลัก", "เทียบ")}

    # ค่าถือขา short: กำไรของไม้ทนค่าถือต่อรอบได้กี่รอบ
    per_round = D(str(acct["ค่าถือคู่"]["ต่อรอบ"]))
    hold = {"ต่อรอบ": float(per_round), "รอบที่กินไม้1": q(D(win) / per_round, 0),
            "รอบที่กินไม้2": q(D(res[1]) / per_round, 0)}
    rps = int(acct["ค่าถือคู่"]["รอบต่อช่วง"])
    paths = c["เส้นทาง"]
    for k in ("1", "2", "3", "4"):
        rounds = int(paths[k]["ช่วงที่ถือ"]) * rps
        assert q(per_round * rounds, 1) == q(D(str(paths[k]["ค่าถือ"])), 1)       # ตรงกับ sab_figures.py
        hold[f"รอบ{k}"] = rounds
        hold[f"สุทธิถ้าจ่าย{k}"] = q(D(str(paths[k]["สุทธิ"])) - per_round * rounds, 1)   # funding ติดลบเท่ากัน
    # 📒 ไม้จริง 1–2 ของมินเดินเหมือนเส้นทาง 1, 2 · funding +0.01% ตลอด (สมมติ) → ขา A ที่ short รับ
    hold["ค่าถือไม้1ไม้2"] = q(D(str(paths["1"]["ค่าถือ"])) + D(str(paths["2"]["ค่าถือ"])), 1)
    hold["บัญชีคู่หลังค่าถือ"] = q(D(str(paths["1"]["สุทธิหลังค่าถือ"])) + D(str(paths["2"]["สุทธิหลังค่าถือ"])), 1)
    hold["ไม้3ค่าถือถึงตอนนี้"] = q(per_round * rps, 1)                              # ถือมา 1 ช่วง

    # กฎ 1%: ถ้ากระโดดแบบเส้นทาง 3 (2.1 → 4.1) ต้องลดเหลือกี่ชุด
    p3 = c["เส้นทาง"]["3"]
    per_set = (D(str(p3["Xออก"])) - D(str(p3["Xเข้า"]))) + cost / sets          # 2.1 ต่อชุด
    cap = D(str(c["กฎ1"]["เพดานต่อไม้"]))
    fit_sets = int(cap // per_set)
    fit_loss = q(-per_set * fit_sets, 2)
    rule = {"เสียต่อชุดถ้ากระโดด": q(per_set, 2), "ชุดที่ไม่เกินกฎ": fit_sets, "เสียถ้ากระโดด": fit_loss,
            "เสียเปอร์เซ็นต์ทุนรวม": q(-D(str(fit_loss)) / D(str(c["กฎ1"]["ทุนรวมดอลลาร์"])) * 100, 2)}

    # ✍️ (ก) เข้าที่ 2.4 · ออกที่ 0.3 · กระโดดไป 4.6
    e, xo, xj = D("2.4"), D("0.3"), D("4.6")
    ex_win = q(sets * (e - xo) - cost, 0)
    ex_lose = q(sets * (e - xj) - cost, 0)
    ex_line = q(e + (-D(str(card["งบขาดทุนสุทธิ"])) - cost) / sets, 1)
    ex_rate = q(D(-ex_lose) / D(ex_win - ex_lose) * 100, 2)
    # ✍️ (ค) ต้นทุนเข้า + ออกเป็น 3 แทน 1 (เปลี่ยนกติกาหนึ่งข้อ)
    c3 = D(3)
    t_res = [q(D(r) + cost - c3, 0) for r in res]
    t_rate = q(D(-t_res[2]) / D(t_res[0] - t_res[2]) * 100, 2)
    mix = c["สัดส่วนตอนจบ"]["หลัก"]["สัดส่วน"]
    t_ev = q(sum(D(m) * D(r) for m, r in zip(mix, t_res)) / 100, 2)

    claims = [{"id": "ch12-informed-gap",
               "ข้อความ": ("เมื่อมีข่าวที่เปลี่ยนความสัมพันธ์ของสองเหรียญถาวร (ถูกถอดจากตลาด · ถูกเจาะ · ปลดล็อกโทเคนก้อนใหญ่ · "
                           "กติกาเปลี่ยน) คนที่รู้ก่อนซื้อขายก่อนราคาสะท้อนครบ ระยะของคู่จึงมักกระโดดแทนที่จะค่อย ๆ ถ่าง "
                           "และราคาที่ปิดได้อยู่เลยเส้นงบ · คนที่ขายเพราะต้องการเงินด่วนดูจากราคาเหมือนกัน แต่ระยะหดกลับ "
                           "— ในเวลาจริงแยกสองแบบไม่ออก"),
               "ระดับหลักฐาน": "สมมติฐาน", "แหล่ง": None, "บท": [12, 14]}]

    drills = [
        {"โจทย์": "การ์ดเดิม เข้า short X ที่ 2.4 · (1) ออกที่ 0.3 ได้สุทธิเท่าไร (2) กระโดดไป 4.6 เสียเท่าไร "
                            "(3) ต้องชนะกี่ % (สองตอนจบ)", "เส้นงบ": ex_line,
         "คำตอบ": [ex_win, ex_lose, ex_rate]},
        {"โจทย์": "งบ −15 เกินกฎ 1% และกระโดดแบบเส้นทาง 3 เสีย 1.47% · ต้องลดเหลือกี่ชุดจึงไม่เกิน 14.29",
         "คำตอบ": [fit_sets, fit_loss, rule["เสียเปอร์เซ็นต์ทุนรวม"]]},
        {"โจทย์": "ย้ายไปที่ต้นทุนเข้า + ออกเป็น 3 · สามตอนจบใหม่ · อัตราชนะที่ต้องได้ · ค่าคาดหมายที่ 60/25/15",
         "คำตอบ": t_res + [t_rate, t_ev]},
    ]
    return {
        "รายขา": _paths_legs(data, D, q),
        "ต้นทุนต่อชุด": q(cost / sets, 1),
        "ชนะ37": count37,
        "ค่าคาดหมาย100ไม้": ev,
        "แถบผล": strip,
        "สองไม้แรกไม่ชนงบเปอร์เซ็นต์": no_hit,
        "ค่าถือขาshort": hold,
        "กฎ1ทางรอด": rule,
        "แบบฝึกก": {"เข้า": float(e), "ออก": float(xo), "กระโดด": float(xj), "สุทธิออก": ex_win,
                    "สุทธิกระโดด": ex_lose, "เส้นงบ": ex_line, "ต้องชนะ": ex_rate},
        "แบบฝึกค": {"ต้นทุน": 3, "สามตอนจบ": t_res, "ต้องชนะ": t_rate, "ค่าคาดหมาย": t_ev},
        "_claims": claims,
        "_แบบฝึก": drills,
    }
