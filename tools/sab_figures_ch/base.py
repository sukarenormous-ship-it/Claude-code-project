"""ภาคพื้นฐาน "คืนก่อนวันที่ 1" (docs/sab-base1..4.html · แผน 14.5) — ตัวเลขของหน้าพื้นฐาน

ปลั๊กอินของ tools/sab_figures.py · ค่าที่คืนลงใต้ data["base"] · รันก่อน ch00
แยกคีย์ย่อยต่อหน้า: b1 (ซื้อก่อนขายทีหลัง) · b2 (ขายก่อนซื้อคืน) · b3 (สองขาในชุดเดียว) · b4 (สัญญามีวันหมดอายุ · เงินสามกอง)
เหรียญฝึกสองตัว A ราคา 100 และ B ราคา 50 (ดอลลาร์ สมมติ) — คู่เดียวกับบท 9–11 (ชุด = ซื้อ A 1 · ขาย B 2 · X = A − 2B)
ทุกค่าคำนวณจากราคาตั้งต้นและราคาตอนปิดที่ประกาศในไฟล์นี้ · ไม่มีผลลัพธ์พิมพ์ลอย · ยังไม่คิดค่าธรรมเนียม (ยกเว้นแบบฝึก b4 ข้อ 3)
"""


def extend(data, D, q):
    A0, B0 = D(100), D(50)
    i = lambda x: q(x, 0)          # noqa: E731  จำนวนเต็ม
    f1 = lambda x: q(x, 1)         # noqa: E731  ทศนิยมหนึ่งตำแหน่ง

    def num(x):                    # จำนวนเต็มเมื่อลงตัว (พิมพ์ "1" ไม่ใช่ "1.0") · ไม่ลงตัวเก็บหนึ่งตำแหน่ง
        x = D(x)
        return i(x) if x == x.to_integral() else f1(x)

    # ───────── b1 ซื้อไว้ก่อน แล้วขายทีหลัง (A) ─────────
    def long_trade(n, buy, sell):
        n, buy, sell = D(n), D(buy), D(sell)
        return {"จำนวน": i(n), "ราคาซื้อ": i(buy), "ราคาขาย": i(sell), "จ่าย": i(n * buy), "รับ": i(n * sell),
                "ผลต่อหน่วย": i(sell - buy), "ผล": i(n * sell - n * buy)}

    one = long_trade(1, A0, 102)
    two = long_trade(2, A0, 99)
    assert two["ผล"] == two["จำนวน"] * two["ผลต่อหน่วย"]
    tomorrow = D(102)
    hold = {"จำนวน": 2, "จ่ายไปแล้ว": two["จ่าย"],
            "มูลค่าหลังซื้อ": i(2 * A0),
            "ราคาคืนนี้": two["ราคาขาย"], "มูลค่าคืนนี้": i(2 * D(two["ราคาขาย"])),
            "ต่างคืนนี้": i(2 * D(two["ราคาขาย"]) - D(two["จ่าย"])),
            "ราคาพรุ่งนี้": i(tomorrow), "มูลค่าพรุ่งนี้": i(2 * tomorrow),
            "ต่างพรุ่งนี้": i(2 * tomorrow - D(two["จ่าย"]))}
    b1_ex = {"ข้อ1": long_trade(1, A0, 97), "ข้อ2": long_trade(3, A0, 102)}
    screen, later = D(104), D(98)
    b1_ex["ข้อ3"] = {"จำนวน": 2, "จ่าย": i(2 * A0), "ราคาจอ": i(screen), "มูลค่าตามจอ": i(2 * screen),
                     "ต่างตามจอ": i(2 * screen - 2 * A0), "ราคาตอนขาย": i(later), "รับ": i(2 * later),
                     "ผล": i(2 * later - 2 * A0)}
    b1 = {"A": i(A0), "หนึ่งหน่วย": one, "สองหน่วย": two, "ยังไม่ขาย": hold, "แบบฝึก": b1_ex,
          "แกนกราฟ": [-200, -100, 0, 100, 200]}

    # ───────── b2 ขายก่อน แล้วซื้อคืนทีหลัง (B) ─────────
    def short_trade(n, sell, buyback):
        n, sell, buyback = D(n), D(sell), D(buyback)
        return {"จำนวน": i(n), "ราคาขาย": i(sell), "ราคาซื้อคืน": i(buyback), "ขายรวม": i(n * sell),
                "ซื้อคืนรวม": i(n * buyback), "ผลต่อหน่วย": i(sell - buyback), "ผล": i(n * sell - n * buyback)}

    b2 = {"B": i(B0),
          "ยืมมาขาย": short_trade(1, B0, 51),
          "ตกลงขาย": {"ขึ้น": short_trade(1, B0, 51), "ลง": short_trade(1, B0, 49)},
          "สองหน่วย": {"ขึ้น": short_trade(2, B0, 51), "ลง": short_trade(2, B0, 49)},
          "เทียบlong": {"A": one, "B": short_trade(1, B0, 51)},
          "แกนราคา": [47, 48, 49, 50, 51, 52, 53],
          "แบบฝึก": {"ข้อ1": short_trade(1, B0, 47), "ข้อ2": short_trade(3, B0, 52),
                     "ข้อ3": dict(short_trade(1, B0, 55), เงินที่รับตอนขาย=i(B0))}}
    b2["กราฟ"] = {"short1": [i(B0 - p) for p in map(D, b2["แกนราคา"])],
                  "long1": [i(p - B0) for p in map(D, b2["แกนราคา"])]}

    # ───────── b3 สองขาในชุดเดียว: ซื้อ A 1 ที่ 100 · ขาย B 2 ที่ 50 ─────────
    nA, nB = D(1), D(2)

    def pair_end(name, a1, b1_, a0=A0, b0=B0):
        a1, b1_, a0, b0 = D(a1), D(b1_), D(a0), D(b0)
        legA, legB = nA * (a1 - a0), nB * (b0 - b1_)
        cash_in = nB * b0 + nA * a1          # ขาย B ตอนเปิด + ขาย A ตอนปิด
        cash_out = nA * a0 + nB * b1_        # ซื้อ A ตอนเปิด + ซื้อ B คืนตอนปิด
        assert cash_in - cash_out == legA + legB
        assert (a1 - nB * b1_) - (a0 - nB * b0) == legA + legB
        return {"ชื่อ": name, "A": i(a1), "B": num(b1_),
                "ขาA": i(legA), "ขาB": i(legB), "รวม": i(legA + legB),
                "รับรวม": i(cash_in), "จ่ายรวม": i(cash_out), "Aลบ2B": i(a1 - nB * b1_), "ซื้อBคืนรวม": i(nB * b1_)}

    ends = [pair_end("เสียทั้งสองขา", 99, 51), pair_end("ได้ทั้งสองขา", 101, 49),
            pair_end("หักกันพอดี", 102, 51), pair_end("ได้ไม่เท่ากัน", 104, 51)]
    up1, dn1 = D("1.01"), D("0.99")

    def move(mult, nb):
        a1, bb = A0 * mult, B0 * mult
        legA, legB = a1 - A0, D(nb) * (B0 - bb)
        return {"A": num(a1), "B": num(bb), "Bต่อหน่วย": num(bb - B0), "ขาA": num(legA), "ขาB": num(legB),
                "รวม": num(legA + legB)}

    b3 = {"เปิด": {"A": i(A0), "B": i(B0), "จำนวนA": i(nA), "จำนวนB": i(nB), "จ่ายA": i(nA * A0), "รับB": i(nB * B0),
                   "เงินสดตอนเปิด": i(nB * B0 - nA * A0), "Aลบ2B": i(A0 - nB * B0)},
          "ตอนจบ": ends,
          "ทำไมสองB": {"ขึ้น1%": {"สองB": move(up1, 2), "หนึ่งB": move(up1, 1)},
                       "ลง1%": {"สองB": move(dn1, 2), "หนึ่งB": move(dn1, 1)}},
          "แกนกราฟ": [-4, -2, 0, 2, 4]}
    e2_open_B = D(52)
    b3["แบบฝึก"] = {
        "ข้อ1": pair_end("ลงทั้งคู่", 98, 49),
        "ข้อ2": dict(pair_end("เปิดที่ B 52 ปิดที่ราคาเดิม", 100, 52, b0=e2_open_B),
                     รับBตอนเปิด=i(nB * e2_open_B), เงินสดตอนเปิด=i(nB * e2_open_B - nA * A0)),
        "ข้อ3": {"ขึ้น2%": {"หนึ่งB": {"ขาA": 2, "ขาB": -1, "รวม": 1}, "สองB": {"ขาA": 2, "ขาB": -2, "รวม": 0}},
                 "ลง2%": {"หนึ่งB": {"ขาA": -2, "ขาB": 1, "รวม": -1}, "สองB": {"ขาA": -2, "ขาB": 2, "รวม": 0}}},
    }
    for k, (mult, a1, b1_) in {"ขึ้น2%": (D("1.02"), 102, 51), "ลง2%": (D("0.98"), 98, 49)}.items():
        assert A0 * mult == a1 and B0 * mult == b1_
        for nb, key in ((1, "หนึ่งB"), (2, "สองB")):
            r = b3["แบบฝึก"]["ข้อ3"][k][key]
            assert r["ขาA"] == a1 - A0 and r["ขาB"] == nb * (B0 - b1_) and r["รวม"] == r["ขาA"] + r["ขาB"]

    # ───────── b4 สัญญามีวันหมดอายุ · เงินสามกอง (B spot 50 · สัญญา 3 เดือน 51) ─────────
    S0, F0, months = D(50), D(51), 3

    def expiry(s_end, s0=S0, f0=F0):
        s_end, s0, f0 = D(s_end), D(s0), D(f0)
        spot_leg, fut_leg = s_end - s0, f0 - s_end          # ซื้อ spot 1 · ขายสัญญา 1 · สัญญาจบที่ราคา spot วันนั้น
        return {"spotวันหมดอายุ": i(s_end), "สัญญาจบที่": i(s_end), "ขาspot": i(spot_leg), "ขาสัญญา": i(fut_leg),
                "รวม": i(spot_leg + fut_leg), "ห่างตอนเปิด": i(f0 - s0)}

    endA, endB = expiry(53), expiry(48)
    assert endA["รวม"] == endB["รวม"] == F0 - S0
    gaps = [D(1), D("0.7"), D("0.4"), D(0)]
    pathA = [D(50), D(51), D(52), D(53)]
    pathB = [D(50), D("49.5"), D("48.5"), D(48)]
    mid_s, mid_f = D(52), D("52.5")
    cash0 = D(100)
    rows = [("เริ่ม", cash0, 0, 0), ("ซื้อBspot", cash0 - S0, S0, 0), ("ขายสัญญา", cash0 - S0, S0, 0),
            ("กลางทาง", cash0 - S0, mid_s, F0 - mid_f), ("วันหมดอายุ", cash0 - S0, D(53), F0 - D(53)),
            ("ปิดครบ", cash0 - S0 + D(53) - (D(53) - F0), 0, 0)]
    acc = [{"จังหวะ": n, "เงินสด": num(c), "มูลค่าB": num(b), "สัญญา": num(k), "equity": num(c + b + k)}
           for n, c, b, k in rows]
    assert acc[-1]["equity"] == acc[-2]["equity"] == i(cash0 + endA["รวม"])
    fee, n_fee = D("0.5"), 4   # สี่ครั้งตามแบบของเล่ม (เปิดสองขา · ปิดสองขา รวมการปิดสัญญาในวันหมดอายุ)
    b4 = {"spot": i(S0), "สัญญา": i(F0), "เดือน": months, "ห่าง": i(F0 - S0),
          "ห่างต่อเงินที่ซื้อเปอร์เซ็นต์": q((F0 - S0) / S0 * 100, 0),
          "จบก": endA, "จบข": endB,
          "เส้นทาง": {"เดือน": [0, 1, 2, 3],
                      "ก": {"spot": [f1(x) for x in pathA], "สัญญา": [f1(x + g) for x, g in zip(pathA, gaps)]},
                      "ข": {"spot": [f1(x) for x in pathB], "สัญญา": [f1(x + g) for x, g in zip(pathB, gaps)]}},
          "กลางทาง": {"spot": i(mid_s), "สัญญา": f1(mid_f), "ห่าง": f1(mid_f - mid_s), "ขาspot": i(mid_s - S0),
                      "ขาสัญญา": f1(F0 - mid_f), "equityเปลี่ยน": f1(mid_s - S0 + F0 - mid_f)},
          "บัญชี": acc, "เงินสดตั้งต้น": i(cash0), "ขายBวันหมดอายุ": 53, "จ่ายส่วนต่างสัญญา": i(D(53) - F0),
          "แบบฝึก": {"ข้อ1": expiry(55), "ข้อ2": expiry(47, f0=D(52)),
                     "ข้อ3": {"ค่าธรรมเนียมต่อครั้ง": f1(fee), "จำนวนครั้ง": n_fee, "ค่าธรรมเนียมรวม": f1(fee * n_fee),
                              "ก่อนค่าธรรมเนียม": i(F0 - S0), "หลังค่าธรรมเนียม": f1(F0 - S0 - fee * n_fee)}}}

    return {
        "b1": b1, "b2": b2, "b3": b3, "b4": b4,
        "_แบบฝึก": [
            {"โจทย์": "b1 ข้อ 1 · ซื้อ A 1 หน่วยที่ 100 ขายที่ 97 · ผลเท่าไร", "คำตอบ": b1_ex["ข้อ1"]["ผล"]},
            {"โจทย์": "b1 ข้อ 2 · ซื้อ A 3 หน่วยที่ 100 ขายที่ 102 · ผลเท่าไร", "คำตอบ": b1_ex["ข้อ2"]["ผล"]},
            {"โจทย์": "b2 ข้อ 2 · ขายก่อน B 3 หน่วยที่ 50 ซื้อคืนที่ 52 · ผลเท่าไร", "คำตอบ": b2["แบบฝึก"]["ข้อ2"]["ผล"]},
            {"โจทย์": "b3 ข้อ 1 · ซื้อ A 1 ที่ 100 ขาย B 2 ที่ 50 · ปิดที่ A 98 B 49 · ผลรวม", "คำตอบ": b3["แบบฝึก"]["ข้อ1"]["รวม"]},
            {"โจทย์": "b4 ข้อ 2 · ซื้อ B spot 50 ขายสัญญา 52 · วันหมดอายุ spot 47 · ผลรวม", "คำตอบ": b4["แบบฝึก"]["ข้อ2"]["รวม"]},
        ],
    }
