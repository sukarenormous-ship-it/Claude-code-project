    def mini(x):
        v = D(str(x)) * scale
        return int(v) if v == v.to_integral() else q(v, 2)

    # ── v2: ผลกลางทางสำหรับ "แสดงการคิด" (ยืดเงินเป็นต่อปีก่อน แล้วหารด้วยตัวหาร) ──
    def yr(x, d=days):                              # เงินต่อช่วง → เงินต่อปี (simple)
        return x * year / d

