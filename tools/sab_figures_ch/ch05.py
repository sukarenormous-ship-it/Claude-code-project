"""บท 5 — 12.17% บนจอ เหลือ 5.23% ในมือ · ค่าที่บทพิมพ์แต่ยังไม่มีใน JSON หลัก

ทุกค่าคำนวณจาก บัญชีมิน + ch05 เดิม (บันได · บันไดแย่ง · ทุนกับกันชน) + ch04 (กันชน)
อัตราต่อปีทั้งบทเป็นแบบ simple: เปอร์เซ็นต์ต่อช่วง × 365 ÷ วันที่เหลือ
ค่าธรรมเนียม taker 0.05% ต่อครั้ง · สามครั้ง: ซื้อ spot · short futures · ขาย spot วันหมดอายุ (ราคาชำระสมมติ 105,000)
"""


def extend(data, D, q):
    m, c5 = data["บัญชีมิน"], data["ch05"]
    btc = m["BTC"]
    year = D(365)
    s0, f0, settle = D(btc["spot"]), D(btc["futures"]), D(btc["ราคาชำระ"])
    days = D(btc["วันถึงหมดอายุ"])
    cap = D(m["ทุนภาค1"]["รวม"])
    fee = D(str(m["ค่าธรรมเนียม"]["taker"])) / 100
    hurdle = D(str(m["hurdle"])) / 100
    scale = D(str(m["สเกล"]))
    basis = f0 - s0
    lad = c5["บันได"]

    def ann(x, base, d=days):                       # ต่อช่วง → ต่อปีแบบ simple (%)
        return x / base * year / d * 100

    def fees_for(fut, settle_px=settle, s=s0, r=fee):
        return r * (s + fut + settle_px)

    traded = s0 + f0 + settle
    opp = cap * hurdle * days / year
    # basis ต่ำสุดที่ยังคุ้ม: basis − ค่าธรรมเนียม(basis) − ค่าเสียโอกาส = 0
    #   ค่าธรรมเนียม = r·(S + S + basis + ราคาชำระ) → basis·(1 − r) = ค่าเสียโอกาส + r·(2S + ราคาชำระ)
    be_basis = (opp + fee * (2 * s0 + settle)) / (1 - fee)

    # ── ✍️ ข้อ 1–2: spot 60,000 · futures 61,200 · 60 วัน · ทุน 75,000 · ราคาชำระสมมติ = 61,200 ──
    ex = data["แบบฝึก"]["ch05"][0]
    es, ef, ed, ecap = D(ex["spot"]), D(ex["futures"]), D(ex["วัน"]), D(ex["ทุน"])

    def ladder(spot, fut, d, capital, settle_px):
        b = fut - spot
        fe = fee * (spot + fut + settle_px)
        net = b - fe
        o = capital * hurdle * d / year
        return {"spot": q(spot, 0), "futures": q(fut, 0), "วัน": int(d), "ทุน": q(capital, 0), "basis": q(b, 0), "basisเปอร์เซ็นต์": q(b / spot * 100, 2),
                "บนจอ": q(ann(b, spot, d), 2), "ต่อทุน": q(ann(b, capital, d), 2),
                "ค่าธรรมเนียม": q(fe, 2), "สุทธิ": q(net, 2), "หลังค่าธรรมเนียม": q(ann(net, capital, d), 2),
                "ค่าเสียโอกาส": q(o, 2), "ส่วนเกิน": q(net - o, 2), "ส่วนเกินเปอร์เซ็นต์": q(ann(net - o, capital, d), 2)}

    ex1 = ladder(es, ef, ed, ecap, ef)
    half_f = es + (ef - es) / 2
    ex2 = ladder(es, half_f, ed, ecap, half_f)

    # ── ✍️ ข้อ 3 (ถ่ายโอน): exchange กติกาหลักประกัน 20% · อยากได้กันชน 13% ของราคา futures เท่าเดิม ──
    r20, target = D("0.20"), D(13)
    m20 = r20 * f0
    free20 = target / 100 * f0 * (1 + r20)          # เงินสดอิสระที่ต้องมี = กันชนเป็นเงิน × ตัวคูณ
    cap20 = s0 + m20 + free20
    net = D(str(lad["สุทธิ"]))
    opp20 = cap20 * hurdle * days / year
    ex3 = {"หลักประกันเริ่ม": q(m20, 0), "เงินสดอิสระที่ต้องมี": q(free20, 0), "ทุน": q(cap20, 0),
           "ค่าเสียโอกาส": q(opp20, 2), "ส่วนเกิน": q(net - opp20, 2),
           "ส่วนเกินเปอร์เซ็นต์": q(ann(net - opp20, cap20), 2), "กันชนเป้า": int(target)}

    caps = {str(r["ทุน"]): r for r in c5["ทุนกับกันชน"]}
    ton_extra = D(str(caps["120000"]["ส่วนเกินเปอร์เซ็นต์"])) - D(str(caps["125000"]["ส่วนเกินเปอร์เซ็นต์"]))

    def mini(x):
        return q(D(str(x)) * scale, 2)

    out = {
        "วันต่อปี": int(year),
        "ตัวคูณต่อปี": q(year / days, 2),                                  # 365 ÷ 90 ≈ 4.06
        "basisเปอร์เซ็นต์ต่อช่วง": q(basis / s0 * 100, 2),                 # 3 ต่อ 90 วัน
        "ต่อทุนต่อช่วง": q(basis / cap * 100, 2),                          # 2.4 ต่อ 90 วัน
        "สุทธิต่อช่วง": q(net / cap * 100, 2),
        "มูลค่าซื้อขายรวม": q(traded, 0),
        "ค่าธรรมเนียมรายครั้ง": {"ซื้อspot": q(fee * s0, 2), "shortfutures": q(fee * f0, 2),
                                "ขายspotวันหมดอายุ": q(fee * settle, 2)},
        "ขั้นที่หาย": {"ตัวหาร": q(D(str(lad["บนจอ"])) - D(str(lad["ต่อทุน"])), 2),
                       "ค่าธรรมเนียม": q(D(str(lad["ต่อทุน"])) - D(str(lad["หลังค่าธรรมเนียม"])), 2),
                       "hurdle": q(D(str(lad["หลังค่าธรรมเนียม"])) - D(str(lad["ส่วนเกินเปอร์เซ็นต์"])), 2)},
        "hurdleต่อช่วง": q(hurdle * days / year * 100, 2),
        "basisคุ้มทุน": q(be_basis, 0),
        "basisคุ้มทุนบนจอ": q(ann(be_basis, s0), 2),
        "ต้นได้เพิ่มเปอร์เซ็นต์": q(ton_extra, 2),
        "ของมิน": {"basis": mini(basis), "ทุน": mini(cap), "ค่าธรรมเนียม": mini(lad["ค่าธรรมเนียม"]),
                   "สุทธิ": mini(lad["สุทธิ"]), "ค่าเสียโอกาส": mini(lad["ค่าเสียโอกาส"]),
                   "ส่วนเกิน": mini(lad["ส่วนเกิน"]), "basisคุ้มทุน": mini(q(be_basis, 0))},
        # ทุน 150,000 (06.08 ข้อ 1 · เดิมอยู่ใน แบบฝึก.ch05 ซึ่งปลั๊กอินนี้แทนด้วย ✍️ ใหม่)
        "ทุน150000": {"ค่าเสียโอกาส": q(D(150000) * hurdle * days / year, 2),
                      "ส่วนเกิน": q(net - D(150000) * hurdle * days / year, 2),
                      "หลังค่าธรรมเนียม": q(ann(net, D(150000)), 2)},
        "แบบฝึก1": ex1,
        "แบบฝึก2": ex2,
        "แบบฝึก3": ex3,
        "_claims": [
            {"id": "ch05-crowding-basis",
             "ข้อความ": "เมื่อคนทำ cash-and-carry มากขึ้น แรงซื้อ spot และแรงขาย futures ดันให้ basis แคบลง · ขนาดที่แคบลง"
                        "ขึ้นกับจำนวนคนที่ยอมจ่ายฝั่ง long ด้วย — ตัวเลขบันไดแย่งในบท 5 เป็นตัวเลขสมมติ ไม่ใช่ข้อมูลตลาด",
             "ระดับหลักฐาน": "สมมติฐาน", "แหล่ง": None, "บท": [5]},
            {"id": "ch05-cme-basiswatch",
             "ข้อความ": "CME มีเครื่องมือแสดง basis ของ futures คริปโตเทียบ spot และอัตราต่อปีที่ราคาตลาดสะท้อน — "
                        "อัตรานั้นเทียบกับราคา spot ไม่ใช่ผลตอบแทนของทุนที่ผู้ถือต้องผูกไว้",
             "ระดับหลักฐาน": "มีแหล่ง",
             "แหล่ง": "R20 · CME Group, Cryptocurrency BasisWatch and Implied Rate Tool (อ้างในต้นฉบับ v0.9 · ยังไม่ได้เปิดตรวจหน้าเว็บในเฟสนี้)",
             "บท": [5]},
        ],
        "_แบบฝึก": [
            {"โจทย์": "spot 60,000 futures 61,200 เหลือ 60 วัน ทุน 75,000 · taker 0.05% สามครั้ง (ราคาชำระ = 61,200) · "
                      "hurdle 4% → บันไดสี่ขั้น", **ex1,
             "คำตอบ": [ex1["บนจอ"], ex1["ต่อทุน"], ex1["หลังค่าธรรมเนียม"], ex1["ส่วนเกินเปอร์เซ็นต์"]]},
            {"โจทย์": "ชุดเดียวกันแต่ basis เหลือครึ่ง (futures 60,600) → บนจอยังเกิน 4% ควรเปิดไหม",
             **ex2, "คำตอบ": [ex2["บนจอ"], ex2["ส่วนเกินเปอร์เซ็นต์"]]},
            {"โจทย์": "exchange กติกาหลักประกัน 20% · อยากได้กันชน 13% เท่ามิน → ทุนเท่าไร ส่วนเกินกี่ %",
             **ex3, "คำตอบ": [ex3["ทุน"], ex3["ส่วนเกินเปอร์เซ็นต์"]]},
        ],
    }
    return out
