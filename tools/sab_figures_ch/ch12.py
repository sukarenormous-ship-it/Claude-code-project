    e = D(str(c["จุดเข้า"]))                                     # 2.1
    per_round = D(str(acct["ค่าถือคู่"]["ต่อรอบ"]))
    rps = int(acct["ค่าถือคู่"]["รอบต่อช่วง"])
    total_usd = D(str(acct["กฎ1%"]["ทุนรวมดอลลาร์"]))
    cap1 = D(str(acct["กฎ1%"]["เพดานต่อไม้"]))

    paths = {}
    for k in ("1", "2", "3", "4"):
        p = c["เส้นทาง"][k]
        xs = [D(str(x)) for x in p["X"][1:]]                       # ตั้งแต่จุดเข้า
        assert xs[0] == e
        nets, why, held = [], None, None
        for t, x in enumerate(xs[1:], 1):
            net = sets * (e - x) - cost
            nets.append(q(net, 0))
            if net <= budget:
                why = "งบ"
            elif x <= exit_line:
                why = "เป้า"
            elif t >= max_hold:
                why = "เวลา"
            if why:
                held = t
                break
        assert why == p["เหตุออก"] and held == p["ช่วงที่ถือ"], f"เส้นทาง {k}: เหตุออกเปลี่ยนเมื่อต้นทุน 2"
        gross = D(str(p["กำไรจากราคา"]))
        assert q(sets * (e - xs[held]), 0) == p["กำไรจากราคา"]
        net = gross - cost
        carry = per_round * rps * held
        paths[k] = {"Xออก": float(xs[held]), "กำไรจากราคา": q(gross, 0), "สุทธิ": q(net, 0),
                    "สุทธิถ้าออกตอนนั้น": nets, "ค่าถือ": q(carry, 1),
                    "สุทธิหลังค่าถือ": q(net + carry, 1), "สุทธิถ้าจ่ายค่าถือ": q(net - carry, 1),
                    "รอบ": rps * held, "เหตุออก": why}
