def _hand_sd(xs, mid, D, q):
    """Standard Deviation แบบนับของเล่ม: เรียงระยะจาก Mean (ไม่สนเครื่องหมาย) · ขอบแถบอยู่กึ่งกลางระยะลำดับที่ 2/3 กับลำดับถัดไป"""
    dist = sorted(abs(x - mid) for x in xs)
    k = round(len(xs) * 2 / 3)
    return dist, k, (dist[k - 1] + dist[k]) / 2


